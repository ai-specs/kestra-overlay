import {readFileSync} from 'node:fs';
const [base,directory]=process.argv.slice(2);
const token=JSON.parse(readFileSync(`${directory}/full.json`,'utf8'));
const client=JSON.parse(readFileSync(`${directory}/full.json.client`,'utf8'));
const cookie=JSON.parse(readFileSync(`${directory}/owner-cookies.json`,'utf8')).map(([key,value])=>`${key}=${value}`).join('; ');
const check=(condition,label)=>{if(!condition)throw Error(label);console.log(`PASS ${label}`);};
const initialize=JSON.stringify({jsonrpc:'2.0',id:1,method:'initialize',params:{protocolVersion:'2025-06-18',capabilities:{},clientInfo:{name:'lifecycle',version:'1'}}});
let response=await fetch(`${base}/api/v1/main/mcp/default`,{method:'POST',headers:{Authorization:`Bearer ${token.access_token}`,'Content-Type':'application/json',Accept:'application/json, text/event-stream'},body:initialize});
check(response.status===200,'existing authenticated MCP session initialized');
const session=response.headers.get('mcp-session-id');
await response.text();
check(Boolean(session),'MCP session header retained');
response=await fetch(`${base}/oidc/clients/${client.client_id}`,{headers:{Cookie:cookie}});
check(response.status===200,'owner management detail');
const detail=await response.json();
const form=JSON.stringify({action:'revoke',interaction:detail.interaction});
const csrfPage=await fetch(`${base}/ui/`,{headers:{Cookie:cookie}});
const csrfHtml=await csrfPage.text();
const csrf=csrfHtml.match(/name="csrf-token"[^>]*content="([^"]+)"/)?.[1] || csrfHtml.match(/content="([^"]+)"[^>]*name="csrf-token"/)?.[1];
const mutationHeaders={Cookie:cookie,Origin:base,'Content-Type':'application/json','X-CSRF-TOKEN':csrf||''};
response=await fetch(`${base}/oidc/clients/${client.client_id}/revoke`,{method:'POST',headers:mutationHeaders,body:form});
console.log(`owner mutation status=${response.status}`);
check(response.status===204,'owner revokes client');
response=await fetch(`${base}/oidc/clients/${client.client_id}/revoke`,{method:'POST',headers:mutationHeaders,body:form});
check(response.status===403,'management interaction replay rejected');
response=await fetch(`${base}/api/v1/main/mcp/default`,{method:'POST',headers:{Authorization:`Bearer ${token.access_token}`,'Mcp-Session-Id':session,'Content-Type':'application/json',Accept:'application/json, text/event-stream'},body:JSON.stringify({jsonrpc:'2.0',id:2,method:'tools/call',params:{name:'overlay-acceptance',arguments:{}}})});
check(response.status===401,'revoked token cannot resume existing session or call');
response=await fetch(`${base}/oidc/token`,{method:'POST',headers:{'Content-Type':'application/x-www-form-urlencoded'},body:new URLSearchParams({grant_type:'refresh_token',client_id:client.client_id,refresh_token:token.refresh_token,resource:client.resource})});
check([400,401].includes(response.status),'revoked refresh rejected');
